SELECT
    TABLE_SCHEMA,
    TABLE_NAME,
    COLUMN_NAME,
    ORDINAL_POSITION,
    DATA_TYPE,
    CHARACTER_MAXIMUM_LENGTH,
    NUMERIC_PRECISION,
    NUMERIC_SCALE,
    IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE
       TABLE_NAME LIKE '%Quality%'
    OR TABLE_NAME LIKE '%NonConformance%'
    OR TABLE_NAME LIKE '%EngineeringDocument%'
    OR TABLE_NAME LIKE '%EquipmentMaintenance%'
    OR TABLE_NAME LIKE '%Inspection%'
    OR TABLE_NAME LIKE '%Calibration%'
    OR TABLE_NAME LIKE '%CAPA%'
    OR TABLE_NAME LIKE '%NCR%'
    OR TABLE_NAME LIKE '%Audit%'
    OR TABLE_NAME LIKE '%Product%'
    OR TABLE_NAME LIKE '%Project%'
    OR TABLE_NAME LIKE '%User%'
    OR TABLE_NAME = 'DimDate'
    OR TABLE_NAME = 't_Translations'
ORDER BY TABLE_SCHEMA, TABLE_NAME, ORDINAL_POSITION;